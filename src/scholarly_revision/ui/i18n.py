def language(state: MutableMapping[str, object]) -> str:
    return str(state.get('ui_language', 'en')) if state.get('ui_language') in {'en', 'fa'} else 'en'


def t(key: str, state: MutableMapping[str, object] | None = None, *, lang: str | None = None) -> str:
    selected = lang or (language(state) if state is not None else 'en')
    return TRANSLATIONS.get(selected, TRANSLATIONS['en']).get(key, TRANSLATIONS['en'].get(key, key))


def is_rtl(state: MutableMapping[str, object]) -> bool:
    return language(state) == 'fa'


def status_label(value: object, state: MutableMapping[str, object]) -> str:
    raw = str(getattr(value, 'value', value))
    key = f'status_{raw.lower()}'
    translated = t(key, state)
    return translated if translated != key else raw.replace('_', ' ').title()
